export function getWilayaById(id: number) {
  return algerianWilayas.find(wilaya => wilaya.id === id)
}

export function getWilayaByCode(code: string) {
  return algerianWilayas.find(wilaya => wilaya.code === code)
}

export function getWilayasByZone(zone: string) {
  return algerianWilayas.filter(wilaya => wilaya.zone === zone)
}

export function calculateDeliveryFee(wilayaId: number, orderWeight = 0) {
  const wilaya = getWilayaById(wilayaId)
  if (!wilaya) return null
  
  const baseFee = wilaya.deliveryFee
  
  // Add weight-based fee (per kg)
  const weightFee = Math.ceil(orderWeight) * 100
  const totalFee = baseFee + weightFee
  
  return {
    fee: totalFee,
    estimatedDays: wilaya.estimatedDays,
    baseFee,
    weightFee,
  }
}